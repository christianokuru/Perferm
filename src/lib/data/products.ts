/** Builds variant rows from `[label, priceInNaira, stock, compareAtNaira?]` tuples. */
function variants(slug: string, rows: Array<[string, number, number, number?]>): ProductVariant[] {
  return rows.map(([label, price, stock, compareAt]) => ({
    id: `${slug}-${label.replace(/\s+/g, "").toLowerCase()}`,
    label,
    price: naira(price),
    compareAtPrice: compareAt ? naira(compareAt) : undefined,
    stock,
  }));
}

